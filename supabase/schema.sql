-- 1. USERS TABLE
CREATE TABLE IF NOT EXISTS public.users (
    uid TEXT PRIMARY KEY,
    name TEXT NOT NULL DEFAULT 'User',
    email TEXT,
    phone TEXT,
    gender TEXT DEFAULT 'male',
    profile_image_url TEXT DEFAULT '',
    bio TEXT DEFAULT '',
    dob TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()),
    is_email_verified BOOLEAN DEFAULT FALSE
);

-- Enable Row Level Security (RLS) on users
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

-- Users RLS Policies
DROP POLICY IF EXISTS "Public profiles are readable by authenticated users" ON public.users;
CREATE POLICY "Public profiles are readable by authenticated users"
ON public.users FOR SELECT
TO authenticated, anon
USING (true);

DROP POLICY IF EXISTS "Users can insert their own profile" ON public.users;
CREATE POLICY "Users can insert their own profile"
ON public.users FOR INSERT
TO authenticated
WITH CHECK (auth.uid()::TEXT = uid);

DROP POLICY IF EXISTS "Users can update their own profile" ON public.users;
CREATE POLICY "Users can update their own profile"
ON public.users FOR UPDATE
TO authenticated
USING (auth.uid()::TEXT = uid)
WITH CHECK (auth.uid()::TEXT = uid);

DROP POLICY IF EXISTS "Users can delete their own profile" ON public.users;
CREATE POLICY "Users can delete their own profile"
ON public.users FOR DELETE
TO authenticated
USING (auth.uid()::TEXT = uid);

-- Trigger to automatically create a user profile when new auth account signs up
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.users (uid, name, email, phone, gender, profile_image_url, is_email_verified)
    VALUES (
        new.id::TEXT,
        COALESCE(new.raw_user_meta_data->>'name', 'User'),
        new.email,
        COALESCE(new.raw_user_meta_data->>'phone', new.phone, ''),
        COALESCE(new.raw_user_meta_data->>'gender', 'male'),
        COALESCE(new.raw_user_meta_data->>'profile_image_url', new.raw_user_meta_data->>'avatar_url', ''),
        (new.email_confirmed_at IS NOT NULL)
    )
    ON CONFLICT (uid) DO UPDATE
    SET
        email = EXCLUDED.email,
        is_email_verified = (new.email_confirmed_at IS NOT NULL);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT OR UPDATE ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


-- 2. MATCHES TABLE
CREATE TABLE IF NOT EXISTS public.matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES public.users(uid) ON DELETE CASCADE,
    target_uid TEXT NOT NULL,
    matched_user JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()),
    UNIQUE(user_id, target_uid)
);

-- Enable RLS on matches
ALTER TABLE public.matches ENABLE ROW LEVEL SECURITY;

-- Matches RLS Policies
DROP POLICY IF EXISTS "Users can read own matches" ON public.matches;
CREATE POLICY "Users can read own matches"
ON public.matches FOR SELECT
TO authenticated
USING (auth.uid()::TEXT = user_id);

DROP POLICY IF EXISTS "Users can create own matches" ON public.matches;
CREATE POLICY "Users can create own matches"
ON public.matches FOR INSERT
TO authenticated
WITH CHECK (auth.uid()::TEXT = user_id);

DROP POLICY IF EXISTS "Users can delete own matches" ON public.matches;
CREATE POLICY "Users can delete own matches"
ON public.matches FOR DELETE
TO authenticated
USING (auth.uid()::TEXT = user_id);


-- 3. MESSAGES TABLE
CREATE TABLE IF NOT EXISTS public.messages (
    id TEXT PRIMARY KEY,
    chat_id TEXT NOT NULL,
    sender_id TEXT NOT NULL,
    receiver_id TEXT NOT NULL,
    text TEXT NOT NULL,
    image_url TEXT DEFAULT '',
    timestamp TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()),
    is_read BOOLEAN DEFAULT FALSE
);

-- Ensure image_url column exists if table was created previously
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS image_url TEXT DEFAULT '';

-- Ensure presence columns exist on users
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS is_online BOOLEAN DEFAULT FALSE;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS last_seen TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW());

-- Index for speedy chat retrieval
CREATE INDEX IF NOT EXISTS idx_messages_chat_id_timestamp ON public.messages(chat_id, timestamp);

-- Enable RLS on messages
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

-- Messages RLS Policies
DROP POLICY IF EXISTS "Users can read messages in their conversations" ON public.messages;
CREATE POLICY "Users can read messages in their conversations"
ON public.messages FOR SELECT
TO authenticated
USING (auth.uid()::TEXT = sender_id OR auth.uid()::TEXT = receiver_id);

DROP POLICY IF EXISTS "Users can insert messages as sender" ON public.messages;
CREATE POLICY "Users can insert messages as sender"
ON public.messages FOR INSERT
TO authenticated
WITH CHECK (auth.uid()::TEXT = sender_id);

DROP POLICY IF EXISTS "Users can update read status on received messages" ON public.messages;
CREATE POLICY "Users can update read status on received messages"
ON public.messages FOR UPDATE
TO authenticated
USING (auth.uid()::TEXT = receiver_id)
WITH CHECK (auth.uid()::TEXT = receiver_id);


-- 4. BLOCKED USERS TABLE
CREATE TABLE IF NOT EXISTS public.blocked_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id TEXT NOT NULL REFERENCES public.users(uid) ON DELETE CASCADE,
    blocked_id TEXT NOT NULL REFERENCES public.users(uid) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()),
    UNIQUE(blocker_id, blocked_id)
